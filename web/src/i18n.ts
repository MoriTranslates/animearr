export type I18nKey = keyof typeof en;
const dictionaries: Record<string, Partial<Record<I18nKey, string>>> = { en };
let lang = "en";

export function setLanguage(l: string) {
  lang = dictionaries[l] ? l : "en";
  document.documentElement.lang = lang;
}

export function t(key: I18nKey, vars?: Record<string, string | number | null | undefined>): string {
  const s = dictionaries[lang]?.[key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? "")) : s;
}
